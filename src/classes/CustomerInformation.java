package classes;

public class CustomerInformation {
	int customer_id;
	String last_name;
	String first_name;
	String contact_phone;
	String email;
	public CustomerInformation(int customer_id, String last_name, String first_name, String contact_phone,
			String email) {
		super();
		this.customer_id = customer_id;
		this.last_name = last_name;
		this.first_name = first_name;
		this.contact_phone = contact_phone;
		this.email = email;
	}


}
